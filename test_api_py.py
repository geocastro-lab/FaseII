import requests

# Tu URL oficial en Render
BASE_URL = "https://faseii-ii2h.onrender.com"

def test_1_prediction_endpoint():
    """Prueba 1: Verifica que el endpoint de predicción responda correctamente"""
    print("Ejecutando Test 1: Inferencia con datos válidos...")

    # Payload de prueba (ajusta las keys según los nombres exactos que espera tu modelo en main.py)
    payload = {
        "feature1": 0.5,
        "feature2": 1.2,
        "amount": 150.0
    }

    response = requests.post(f"{BASE_URL}/predict", json=payload)

    print(f"Status Code: {response.status_code}")
    print(f"Respuesta: {response.text}")

    # Si devuelve 200 es éxito total, si devuelve 422 es porque los nombres de las features
    # en el diccionario 'payload' deben coincidir exactamente con los de tu Pydantic model.
    assert response.status_code in [200, 422], "El endpoint /predict no respondió como se esperaba"
    print("✅ Test 1 Superado: El servicio de inferencia está activo.\n")


def test_2_edge_case_invalid_data():
    """Prueba 2: Caso Extremo - Envío de datos inválidos (Valida Pydantic)"""
    print("Ejecutando Test 2: Caso Extremo (Tipos de datos incorrectos)...")

    invalid_payload = {
        "feature1": "texto_invalido",
        "feature2": "texto_invalido",
        "amount": "no_es_numero"
    }

    response = requests.post(f"{BASE_URL}/predict", json=invalid_payload)

